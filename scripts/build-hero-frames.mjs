/**
 * Converts the hero PNG sequence to WebP.
 *
 * The PNG originals live in assets-src/ rather than public/ so Vite does not
 * copy ~86MB of unused source images into every deploy. Only the generated
 * WebP output under public/hero-frames/ is served.
 *
 * Consecutive duplicate frames in the source are "held" frames that create
 * deliberate pauses in the motion. They are encoded once and referenced
 * multiple times by the manifest, so the 191-step timeline is preserved
 * exactly while only unique images are downloaded.
 *
 * Usage: node scripts/build-hero-frames.mjs
 */

import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(ROOT, 'assets-src', 'hero-frames-png');
const OUT_DIR = join(ROOT, 'public', 'hero-frames');
const MANIFEST = join(ROOT, 'frontend', 'components', 'sections', 'frameManifest.js');

const FIRST = 26;
const LAST = 216;
const QUALITY = 88;

const srcName = (n) => `ezgif-frame-${String(n).padStart(3, '0')}.png`;

rmSync(OUT_DIR, { recursive: true, force: true });
mkdirSync(OUT_DIR, { recursive: true });

const hashToSlot = new Map();
const sequence = [];
const uniqueSources = [];
let srcBytes = 0;

for (let n = FIRST; n <= LAST; n++) {
  const path = join(SRC_DIR, srcName(n));
  const buf = readFileSync(path);
  srcBytes += buf.length;

  const hash = createHash('md5').update(buf).digest('hex');
  if (!hashToSlot.has(hash)) {
    hashToSlot.set(hash, uniqueSources.length);
    uniqueSources.push(path);
  }
  sequence.push(hashToSlot.get(hash));
}

console.log(`sequence: ${sequence.length} steps`);
console.log(`unique:   ${uniqueSources.length} images`);
console.log(`encoding at quality ${QUALITY}...`);

let outBytes = 0;
uniqueSources.forEach((src, slot) => {
  const out = join(OUT_DIR, `f${String(slot).padStart(3, '0')}.webp`);
  execFileSync('cwebp', ['-quiet', '-q', String(QUALITY), '-m', '6', src, '-o', out]);
  outBytes += statSync(out).size;
  if ((slot + 1) % 25 === 0 || slot === uniqueSources.length - 1) {
    console.log(`  ${slot + 1}/${uniqueSources.length}`);
  }
});

writeFileSync(
  MANIFEST,
  `// Generated by scripts/build-hero-frames.mjs — do not edit by hand.
// Maps each step of the scroll timeline to a WebP slot. Repeated slots are
// held frames from the source sequence and are downloaded only once.
export const FRAME_SEQUENCE = ${JSON.stringify(sequence)};

export const UNIQUE_FRAME_COUNT = ${uniqueSources.length};

export const framePath = (slot) =>
  \`/hero-frames/f\${String(slot).padStart(3, '0')}.webp\`;
`
);

const mb = (b) => (b / 1024 / 1024).toFixed(1);
console.log(`\n${mb(srcBytes)} MB -> ${mb(outBytes)} MB (${(srcBytes / outBytes).toFixed(1)}x smaller)`);
console.log(`manifest: ${MANIFEST}`);
